"""Generate the M3 feature-switch registry from the ledger (TFG, CPU only; run with python -I).

Inputs, committed next to this tool's directory: FEATURE_SWITCH_MATRIX.tsv (one row per feature; append-only: the bit index
of a feature is its row order, a row is never removed or renumbered) and SHIPPED.tsv (the features whose seam is shipped).
Outputs: M3FeatureIds.java (one int constant per row), M3FeatureTable.java (the rows the registry reads at class
initialization) and FEATURES.tsv (the generated view: bit, constant, alias, shipped). Fixed point: a second run changes
nothing and says so; --check exits 1 when an output would change (the gate of the ledger commit).

Usage: python -I gen_features.py [--check] [--root <worktree>]
"""
import argparse
import re
import sys
from pathlib import Path

HEADER = """/*******************************************************************************
 * Copyright (c) 2026 Synexia, Hitesh Soliwal (hsoliwal@gmail.com) and others.
 *
 * This program and the accompanying materials are made available under the
 * terms of the Apache License, Version 2.0, or (at your option) the Eclipse
 * Public License 2.0, which are available at
 * https://www.apache.org/licenses/LICENSE-2.0 and
 * https://www.eclipse.org/legal/epl-2.0/
 *
 * SPDX-License-Identifier: Apache-2.0 OR EPL-2.0
 *
 * Contributors:
 *     Hitesh Soliwal (Synexia) - initial API and implementation
 *******************************************************************************/
package org.eclipse.swt.internal.render;

"""
LEDGER = "docs/m3/feature-switches/FEATURE_SWITCH_MATRIX.tsv"
SHIPPED = "docs/m3/feature-switches/SHIPPED.tsv"
VIEW = "docs/m3/feature-switches/FEATURES.tsv"
RENDER = "bundles/org.eclipse.swt/Eclipse SWT/common/org/eclipse/swt/internal/render/"
IDS_JAVA = RENDER + "M3FeatureIds.java"
TABLE_JAVA = RENDER + "M3FeatureTable.java"
ID_RE = re.compile(r"^[a-z][a-z0-9-]*$")
ALIAS_RE = re.compile(r"alias: -D([A-Za-z0-9_.]+)=true")
ROW_COLUMNS = ("feature_id", "concept", "widget_family", "current_state", "default", "native_owner",
               "enhanced_api_id", "alias", "shipped")
VIEW_COLUMNS = ("bit", "feature_id", "constant", "concept", "widget_family", "current_state", "default",
                "native_owner", "enhanced_api_id", "alias", "shipped", "switch_key")
NONE = "-"


def read_tsv(path):
    lines = path.read_text(encoding="utf-8").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    header = lines[0].split("\t")
    rows = []
    for number, line in enumerate(lines[1:], start=2):
        cells = line.split("\t")
        if len(cells) != len(header):
            raise SystemExit(f"{path}:{number}: {len(cells)} columns, header has {len(header)}")
        rows.append(dict(zip(header, cells)))
    return rows


def constant_of(feature_id):
    return feature_id.upper().replace("-", "_")


def features(root):
    rows = read_tsv(root / LEDGER)
    shipped = {r["feature_id"] for r in read_tsv(root / SHIPPED)}
    seen = set()
    out = []
    for bit, row in enumerate(rows):
        feature_id = row["feature_id"]
        if not ID_RE.match(feature_id) or feature_id in seen:
            raise SystemExit(f"{LEDGER}: bad or duplicate feature_id {feature_id!r} at bit {bit}")
        seen.add(feature_id)
        alias = ALIAS_RE.search(row["config_surface"])
        out.append({
            "bit": str(bit), "feature_id": feature_id, "constant": constant_of(feature_id),
            "concept": row["concept"], "widget_family": row["widget_family"], "current_state": row["current_state"],
            "default": row["default"], "native_owner": row["native_owner"], "enhanced_api_id": row["enhanced_api_id"],
            "alias": alias.group(1) if alias else NONE, "shipped": "yes" if feature_id in shipped else "no",
            "switch_key": row["switch_key"],
        })
    unknown = shipped - seen
    if unknown:
        raise SystemExit(f"{SHIPPED}: not in the ledger: {sorted(unknown)}")
    if any(r["current_state"] == "NATIVE_HAS" and r["default"] != "on" for r in out):
        raise SystemExit(f"{LEDGER}: a NATIVE_HAS row must default to on")
    return out


def java_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def ids_java(rows):
    body = [HEADER, "/**\n",
            " * The feature ids of the web-UI feature switches: one constant per row of docs/m3/feature-switches/FEATURE_SWITCH_MATRIX.tsv,\n",
            " * its value the row's bit index (append-only, never renumbered). Generated by docs/m3/feature-switches/tools/gen_features.py:\n",
            " * edit the ledger and run the generator, never this file (TFG). Read through {@link M3Features}.\n",
            " */\n",
            "//FLLDCIM: TFG — generated from FEATURE_SWITCH_MATRIX.tsv by gen_features.py; bit index = row order\n",
            "public interface M3FeatureIds {\n"]
    for r in rows:
        body.append(f"\tint {r['constant']} = {r['bit']}; // {r['feature_id']}: {r['widget_family']}, {r['current_state']}, default {r['default']}\n")
    body.append("}\n")
    return "".join(body)


def table_java(rows):
    body = [HEADER, "/**\n",
            " * The rows of the feature-switch ledger the registry reads once at class initialization (TFG: generated by\n",
            " * docs/m3/feature-switches/tools/gen_features.py from FEATURE_SWITCH_MATRIX.tsv and SHIPPED.tsv; edit the ledger, never this\n",
            " * file). One tab-separated string per row, in bit order, columns " + ", ".join(ROW_COLUMNS) + ".\n",
            " */\n",
            "//FLLDCIM: TFG — generated from FEATURE_SWITCH_MATRIX.tsv and SHIPPED.tsv by gen_features.py\n",
            "final class M3FeatureTable {\n",
            "\t/** The number of features: the rows of the ledger. */\n",
            f"\tstatic final int COUNT = {len(rows)};\n",
            "\t/** The columns of a row, tab separated, in bit order. */\n",
            "\tstatic final String [] ROWS = {\n"]
    for r in rows:
        body.append("\t\t" + java_string("\t".join(r[c] for c in ROW_COLUMNS)) + ",\n")
    body += ["\t};\n", "\n", "\tprivate M3FeatureTable () {\n", "\t}\n", "}\n"]
    return "".join(body)


def view_tsv(rows):
    lines = ["\t".join(VIEW_COLUMNS)] + ["\t".join(r[c] for c in VIEW_COLUMNS) for r in rows]
    return "\n".join(lines) + "\n"


def emit(root, relative, text, check):
    path = root / relative
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == text:
        print(f"UNCHANGED\t{relative}")
        return False
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
    print(f"{'WOULD_CHANGE' if check else 'WRITTEN'}\t{relative}")
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when an output would change; write nothing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[4], help="the worktree root")
    args = parser.parse_args()
    rows = features(args.root)
    changed = [emit(args.root, IDS_JAVA, ids_java(rows), args.check),
               emit(args.root, TABLE_JAVA, table_java(rows), args.check),
               emit(args.root, VIEW, view_tsv(rows), args.check)]
    print(f"features={len(rows)} shipped={sum(r['shipped'] == 'yes' for r in rows)} "
          f"native={sum(r['current_state'] == 'NATIVE_HAS' for r in rows)} aliases={sum(r['alias'] != NONE for r in rows)}")
    sys.exit(1 if args.check and any(changed) else 0)


if __name__ == "__main__":
    main()
