"""Measure label repeat ratios (distinct labels / rows) on realistic UI data.

Read-only analysis. Every dataset is a real source; nothing is synthesized
except the SWT differential scripts, whose labels are generated by formulas
that are copied from the test sources and cited per row.

Usage:
  python measure_repeat_ratios.py <fs-root> <json-file> <git-tree-list> <java-src-dir> <out.tsv> [<sample-out.tsv>]

<git-tree-list> is `git ls-tree -r --name-only HEAD` of an Eclipse workspace-like
repository. <sample-out.tsv> receives the first 10^6 file-system rows (name,
type, size, date columns) for the Java benchmark.
"""
import collections
import datetime
import json
import os
import re
import sys

LIMIT = 2_000_000
COLUMNS = ("dataset", "source", "view", "rows", "distinct", "distinct_over_rows",
           "rows_per_distinct", "chars_total", "chars_distinct", "char_saving_pct",
           "top_label", "top_count", "notes")


def row(dataset, source, view, labels, notes="-"):
    counts = collections.Counter(labels)
    rows = sum(counts.values())
    distinct = len(counts)
    chars_total = sum(len(k) * v for k, v in counts.items())
    chars_distinct = sum(len(k) for k in counts)
    top, top_count = counts.most_common(1)[0] if counts else ("", 0)
    top = top.replace("\t", " ").replace("\n", " ")[:40]
    saving = 100.0 * (1 - chars_distinct / chars_total) if chars_total else 0.0
    return (dataset, source, view, rows, distinct, f"{distinct / rows:.4f}" if rows else "0",
            f"{rows / distinct:.1f}" if distinct else "0", chars_total, chars_distinct,
            f"{saving:.1f}", top, top_count, notes)


def explorer_type(name, is_dir):
    if is_dir:
        return "File folder"
    ext = os.path.splitext(name)[1][1:].upper()
    return f"{ext} File" if ext else "File"


def explorer_size(size):
    return f"{max(1, (size + 1023) // 1024):,} KB"


def walk_fs(root):
    """Yields (relative path parts, name, type, size, date) like Windows Explorer columns."""
    stack = [(root, ())]
    seen = 0
    while stack and seen < LIMIT:
        path, parts = stack.pop()
        try:
            entries = sorted(os.scandir(path), key=lambda e: e.name)
        except OSError:
            continue
        for e in entries:
            if seen >= LIMIT:
                break
            try:
                is_dir = e.is_dir(follow_symlinks=False)
                st = e.stat(follow_symlinks=False)
            except OSError:
                continue
            seen += 1
            date = datetime.datetime.fromtimestamp(st.st_mtime).strftime("%Y-%m-%d %H:%M")
            size = "" if is_dir else explorer_size(st.st_size)
            yield parts + (e.name,), e.name, explorer_type(e.name, is_dir), size, date
            if is_dir and e.name != ".git":
                stack.append((e.path, parts + (e.name,)))


def path_rows(dataset, source, paths, sep):
    full = [sep.join(p) for p in paths]
    components = [c for p in paths for c in p]
    nodes = set()
    for p in paths:
        nodes.update(p[:i] for i in range(1, len(p) + 1))
    out = [row(dataset, source, "full path strings", full,
               "one String per row: what a path-keyed expansion map stores"),
           row(dataset, source, "path components", components,
               f"trie nodes={len(nodes)}; component labels are pooled")]
    return out


def fs_rows(root, sample_out):
    names, types, sizes, dates, paths = [], [], [], [], []
    sample = open(sample_out, "w", encoding="utf-8", newline="\n") if sample_out else None
    for parts, name, typ, size, date in walk_fs(root):
        names.append(name)
        types.append(typ)
        sizes.append(size)
        dates.append(date)
        paths.append(parts)
        if sample and len(names) <= 1_000_000:
            sample.write("\t".join(s.replace("\t", " ") for s in (name, typ, size, date)) + "\n")
    if sample:
        sample.close()
    src = f"os.scandir walk of {root} (first {len(names):,} entries, depth-first, sorted)"
    out = [row("file-system", src, "Name column", names),
           row("file-system", src, "Type column", types),
           row("file-system", src, "Size column (files)", [s for s in sizes if s]),
           row("file-system", src, "Date modified column", dates),
           row("file-system", src, "all four columns", names + types + sizes + dates,
               "one pool per table model")]
    return out + path_rows("file-system", src, paths, "/")


def json_nodes(value, parts, out):
    if isinstance(value, dict):
        for k, v in value.items():
            json_nodes(v, parts + (k,), out)
    elif isinstance(value, list):
        for i, v in enumerate(value):
            json_nodes(v, parts + (f"[{i}]",), out)
    if parts:
        out.append((parts, value))


def display(value):
    if isinstance(value, dict):
        return "{...}"
    if isinstance(value, list):
        return f"[{len(value)}]"
    return json.dumps(value, ensure_ascii=False)


def json_rows(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    nodes = []
    json_nodes(data, (), nodes)
    keys = [p[-1] for p, _ in nodes]
    values = [display(v) for _, v in nodes]
    labels = [f"{p[-1]}: {display(v)}" for p, v in nodes]
    src = f"hsoliwal/com.x86core.tools.jsonviewer resources/large-file.json ({len(nodes):,} nodes)"
    out = [row("json-viewer", src, "key column", keys, "array indices shown as [i]"),
           row("json-viewer", src, "value column", values),
           row("json-viewer", src, "key: value label", labels, "single-column tree label")]
    return out + path_rows("json-viewer", src, [p for p, _ in nodes], ".")


def swt_script_rows():
    out = []
    t = "Test_org_eclipse_swt_widgets_Table_ViewportDifferential.java:220 (ROWS=300)"
    out.append(row("swt-differential", t, "Table 3 columns", [f"{c}{i}" for i in range(300)
               for c in ("row ", "cell ", "a longer third cell ")], "unique per row: worst case"))
    tree = "Test_org_eclipse_swt_widgets_Tree_ViewportDifferential.java:130 (ROOTS=300, CHILDREN=40)"
    roots = [f"root {r}" for r in range(300)]
    labels = roots + [f"{r} / {c}" for r in roots for c in range(40)]
    out.append(row("swt-differential", tree, "Tree full-path labels", labels, "label embeds the parent label"))
    segments = roots + [str(c) for _ in roots for c in range(40)]
    out.append(row("swt-differential", tree, "Tree label segments", segments,
                   "same labels as segment ids: parent label id + own segment id"))
    return out


DECL = re.compile(r"^\s*(?:public|protected|private|static|final|abstract|synchronized|\s)*"
                  r"[\w<>\[\], ?]+\s+(\w+)\s*\(([^)]*)\)")


def workspace_rows(tree_list, java_dir):
    with open(tree_list, encoding="utf-8") as f:
        paths = [tuple(line.rstrip("\n").split("/")) for line in f if line.strip()]
    nodes = set()
    for p in paths:
        nodes.update(p[:i] for i in range(1, len(p) + 1))
    names = [n[-1] for n in sorted(nodes)]
    src = f"git ls-tree of hsoliwal/eclipse.platform.swt 5593cc43ba ({len(nodes):,} explorer nodes)"
    out = [row("eclipse-workspace", src, "Project Explorer names", names)]
    out += path_rows("eclipse-workspace", src, sorted(nodes), "/")
    members, params = [], []
    for dirpath, _, files in os.walk(java_dir):
        for fn in files:
            if fn.endswith(".java"):
                with open(os.path.join(dirpath, fn), encoding="utf-8", errors="replace") as f:
                    for line in f:
                        m = DECL.match(line)
                        if m and m.group(1) not in ("if", "for", "while", "switch", "return", "new", "catch"):
                            members.append(m.group(1) + "(" + ", ".join(
                                a.strip().rsplit(" ", 1)[0] for a in m.group(2).split(",") if a.strip()) + ")")
    out.append(row("eclipse-workspace", f"Outline labels of {java_dir}", "Outline member labels", members,
                   "method name(parameter types) as the JDT Outline shows"))
    return out


def main(argv):
    fs_root, json_file, tree_list, java_dir, out_tsv = argv[1:6]
    sample_out = argv[6] if len(argv) > 6 else None
    rows = fs_rows(fs_root, sample_out) + json_rows(json_file) + swt_script_rows() + workspace_rows(tree_list, java_dir)
    with open(out_tsv, "w", encoding="utf-8", newline="\n") as f:
        f.write("\t".join(COLUMNS) + "\n")
        for r in rows:
            f.write("\t".join(str(c) for c in r) + "\n")


if __name__ == "__main__":
    main(sys.argv)
