import java.io.*;
import java.nio.charset.*;
import java.nio.file.*;
import java.util.*;
import java.util.stream.*;

import org.eclipse.swt.m3.*;

/**
 * TFG generator of org/eclipse/swt/m3/M3Languages.tsv (docs/m3/theme-language/README.md): the Hugging Face language tags
 * (HF_LANGUAGE_TAGS.tsv, com.synexia d278d4c1c02) that have a translation model (HF_TRANSLATION_COVERAGE.tsv) and are
 * ISO 639 languages, with the native name from the JDK's CLDR data (source "cldr") or the English name (source "hf"), the
 * script and direction of the native name ({@link M3LanguageId}) and the translation model count. A three-letter ISO 639-2
 * code reads the native name of its two-letter code (<code>ara</code> as <code>ar</code>); the languages the JDK has no
 * native name for and that CLDR's likely subtags put in a right-to-left script come from LIKELY_SCRIPT_OVERRIDES.tsv
 * (source "override"). Deterministic for a JDK
 * version (recorded in the header line); a second run over the same inputs writes the same bytes.
 * <p>
 * Usage: <code>java -cp &lt;swt classes&gt; M3LanguagesGen.java HF_LANGUAGE_TAGS.tsv HF_TRANSLATION_COVERAGE.tsv
 * LIKELY_SCRIPT_OVERRIDES.tsv out.tsv</code>
 * </p>
 */
public class M3LanguagesGen {
	static final Set<String> ISO2 = Set.of (Locale.getISOLanguages ());
	/* ISO 639-2/T three-letter code -> two-letter code, from the JDK */
	static final Map<String, String> ISO3 = ISO2.stream ().collect (Collectors.toMap (code -> Locale.of (code).getISO3Language (), code -> code, (a, b) -> a));
	static Map<String, String []> overrides = Map.of ();

	public static void main (String [] args) throws IOException {
		Map<String, String> names = column (Path.of (args [0]), 0, 1, row -> "yes".equals (row [2]));
		Map<String, String> models = column (Path.of (args [1]), 0, 2, row -> Integer.parseInt (row [2]) > 0);
		overrides = Files.readAllLines (Path.of (args [2]), StandardCharsets.UTF_8).stream ().skip (1).map (line -> line.split ("\t", -1))
			.collect (Collectors.toMap (row -> row [0], row -> row));
		List<String> rows = models.keySet ().stream ().filter (names::containsKey).filter (tag -> language (tag, names.get (tag))).sorted ()
			.map (tag -> row (tag, names.get (tag), models.get (tag))).toList ();
		String head = "# tag\tname\tnative\tscript\tdirection\tmodels\tsource  (generated by M3LanguagesGen, java " + Runtime.version ().feature () + ", " + rows.size () + " languages)";
		Files.writeString (Path.of (args [3]), Stream.concat (Stream.of (head), rows.stream ()).collect (Collectors.joining ("\n", "", "\n")), StandardCharsets.UTF_8);
		System.out.println ("M3Languages.tsv: " + rows.size () + " languages, " + rows.stream ().filter (r -> r.contains ("\trtl\t")).count () + " right-to-left");
	}

	static Map<String, String> column (Path file, int key, int value, java.util.function.Predicate<String []> keep) throws IOException {
		Map<String, String> map = new TreeMap<> ();
		Files.readAllLines (file, StandardCharsets.UTF_8).stream ().skip (1).map (line -> line.split ("\t", -1)).filter (row -> row.length > value)
			.filter (keep).forEach (row -> map.putIfAbsent (row [key], row [value]));
		return map;
	}

	/* ISO 639-1 codes the JDK knows, or three-letter codes with a real English name; no region or script subtags */
	static boolean language (String tag, String name) {
		if (!tag.matches ("[a-z]{2,3}") || name.isBlank () || name.equalsIgnoreCase (tag)) return false;
		return tag.length () == 3 || ISO2.contains (tag);
	}

	/* the JDK knows a native name when it differs from the English one (English itself excepted) */
	static String row (String tag, String name, String models) {
		Locale locale = Locale.forLanguageTag (ISO3.getOrDefault (tag, tag));
		String cldr = locale.getDisplayLanguage (locale);
		boolean known = "en".equals (locale.getLanguage ()) || !cldr.isEmpty () && !cldr.equalsIgnoreCase (tag) && !cldr.equals (locale.getDisplayLanguage (Locale.ENGLISH));
		String nativeName = known ? cldr : name;
		String [] override = overrides.get (tag);
		if (!known && override != null) return String.join ("\t", tag, clean (name), clean (nativeName), override [1], override [2], models, "override");
		int facts = M3LanguageId.detect (nativeName);
		return String.join ("\t", tag, clean (name), clean (nativeName), M3LanguageId.script (facts).name (), M3LanguageId.rightToLeft (facts) ? "rtl" : "ltr",
			models, known ? "cldr" : "hf");
	}

	static String clean (String text) {
		return text.replace ('\t', ' ').strip ();
	}
}
