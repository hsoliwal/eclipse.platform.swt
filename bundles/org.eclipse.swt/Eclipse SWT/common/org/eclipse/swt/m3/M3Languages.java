package org.eclipse.swt.m3;

import java.io.*;
import java.lang.Character.*;
import java.nio.charset.*;
import java.util.*;
import java.util.stream.*;

import org.eclipse.swt.*;

/**
 * The language list of the language switcher (docs/m3/theme-language/README.md): the Hugging Face language tags that have a
 * translation model and are ISO 639 languages (M3Languages.tsv, generated by docs/m3/theme-language/tools/M3LanguagesGen.java
 * from HF_LANGUAGE_TAGS.tsv), each with its English name, native name (the JDK's CLDR data where it has one), script,
 * direction and translation model count. Read once, on first use, into parallel lanes sorted by tag; an entry is an index.
 *
 * @since 3.138
 */
public final class M3Languages {
	private static final String RESOURCE = "M3Languages.tsv";
	private static final int TAG = 0, NAME = 1, NATIVE = 2, SCRIPT = 3, DIRECTION = 4, MODELS = 5, SOURCE = 6;

	private M3Languages () {
	}

	/* the lanes, read on first use (initialization-on-demand holder) */
	private static final class Lanes {
		static final String [][] CELLS = read ();
		static final String [] TAGS = column (TAG);
		static final int [] MODEL_COUNTS = Arrays.stream (CELLS).mapToInt (row -> Integer.parseInt (row [MODELS])).toArray ();
		static final UnicodeScript [] SCRIPTS = Arrays.stream (CELLS).map (row -> UnicodeScript.valueOf (row [SCRIPT])).toArray (UnicodeScript []::new);

		static String [] column (int column) {
			return Arrays.stream (CELLS).map (row -> row [column]).toArray (String []::new);
		}
	}

	static String [][] read () {
		try (InputStream in = M3Languages.class.getResourceAsStream (RESOURCE)) {
			if (in == null) throw new IllegalStateException (RESOURCE + " is missing from the class path");
			BufferedReader reader = new BufferedReader (new InputStreamReader (in, StandardCharsets.UTF_8));
			return reader.lines ().filter (line -> !line.startsWith ("#") && !line.isBlank ()).map (line -> line.split ("\t", -1)).toArray (String [][]::new);
		} catch (IOException e) {
			throw new UncheckedIOException (e);
		}
	}

	/** @return the number of languages */
	public static int count () {
		return Lanes.CELLS.length;
	}

	/** @return the BCP 47 language tag of an entry (<code>ar</code>, <code>de</code>, <code>yue</code> ...) */
	public static String tag (int index) {
		return cell (index, TAG);
	}

	/** @return the English name of an entry */
	public static String name (int index) {
		return cell (index, NAME);
	}

	/** @return the native name of an entry (<code>العربية</code>, <code>Deutsch</code>), the English name when unknown */
	public static String nativeName (int index) {
		return cell (index, NATIVE);
	}

	/** @return the script of an entry's native name (<code>ARABIC</code>, <code>LATIN</code> ...) */
	public static UnicodeScript script (int index) {
		check (index);
		return Lanes.SCRIPTS [index];
	}

	/** @return true for a right-to-left language */
	public static boolean rightToLeft (int index) {
		return "rtl".equals (cell (index, DIRECTION));
	}

	/** @return the number of translation models of an entry on Hugging Face (2026-10-13) */
	public static int models (int index) {
		check (index);
		return Lanes.MODEL_COUNTS [index];
	}

	/** @return where the native name comes from: <code>cldr</code> (the JDK), <code>override</code> (CLDR likely script) or <code>hf</code> (English name) */
	public static String source (int index) {
		return cell (index, SOURCE);
	}

	/** @return the locale of an entry */
	public static Locale locale (int index) {
		return Locale.forLanguageTag (tag (index));
	}

	/**
	 * @param tag a language tag, any case; a region or script subtag is ignored (<code>pt-BR</code> finds <code>pt</code>)
	 * @return the entry of its language, or -1
	 */
	public static int indexOf (String tag) {
		if (tag == null) SWT.error (SWT.ERROR_NULL_ARGUMENT);
		String language = Locale.forLanguageTag (tag.replace ('_', '-')).getLanguage ();
		int at = Arrays.binarySearch (Lanes.TAGS, language);
		return at >= 0 ? at : -1;
	}

	/**
	 * @param count how many
	 * @return the entries with the most translation models, most first (ties by tag)
	 */
	public static int [] top (int count) {
		Comparator<Integer> byModels = Comparator.comparingInt (i -> -Lanes.MODEL_COUNTS [i]);
		return IntStream.range (0, count ()).boxed ().sorted (byModels.thenComparing (i -> Lanes.TAGS [i])).limit (Math.max (0, count)).mapToInt (i -> i).toArray ();
	}

	private static String cell (int index, int column) {
		check (index);
		return Lanes.CELLS [index][column];
	}

	private static void check (int index) {
		if (index < 0 || index >= count ()) SWT.error (SWT.ERROR_INVALID_RANGE);
	}
}
